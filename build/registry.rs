//! The procedures and the IEs of the protocol, read from its ASN.1 once: the list that
//! the macros of the crate and its inspection both expand.
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write;

use anyhow::{Result, anyhow, bail, ensure};
use regex::Regex;

/// The messages of a procedure, as ASN.1 labels each and as a PDU and a kind name it.
pub(crate) const DIRECTIONS: [(&str, &str, &str); 3] = [
    ("INITIATING MESSAGE", "InitiatingMessage", "Initiating"),
    ("SUCCESSFUL OUTCOME", "SuccessfulOutcome", "Successful"),
    (
        "UNSUCCESSFUL OUTCOME",
        "UnsuccessfulOutcome",
        "Unsuccessful",
    ),
];

/// A procedure: its name as the macros take it, the `CRITICALITY` of the elementary
/// procedure that has its code, and the message of each of the [`DIRECTIONS`] that it has.
pub(crate) struct Procedure {
    pub(crate) name: String,
    pub(crate) criticality: Option<String>,
    pub(crate) messages: [Option<Message>; 3],
}

/// A message: the name that ASN.1 gives it, its type, and the IEs of its object set in
/// the order of the set, each as its identifier, its `CRITICALITY` and its `PRESENCE`.
/// A message that has no container of protocol IEs, as a private message, has no
/// object set.
pub(crate) struct Message {
    pub(crate) name: String,
    pub(crate) ty: String,
    pub(crate) ies: Option<Vec<(u16, String, String)>>,
}

/// An IE: the name that ASN.1 gives it after `id-`, the types that its object sets give
/// it and the types that its octets contain, the criticalities that the object sets of
/// the single containers give it, and the names that the macros take it by.
/// The macros take the IE of a message by its own name and, where one type has one IE,
/// by the name of that type and by the aliases that the bindings give the type.
/// An IE of an extension container has the type that the type which it extends gives
/// it: `extends` has each of these types with the types of the bindings that it
/// extends so.
#[derive(Default)]
pub(crate) struct Ie {
    pub(crate) name: String,
    pub(crate) types: BTreeSet<String>,
    pub(crate) extends: BTreeMap<String, BTreeSet<String>>,
    pub(crate) contents: BTreeSet<String>,
    pub(crate) items: BTreeSet<String>,
    pub(crate) macros: Vec<String>,
}

pub(crate) struct Registry {
    /// The module of the bindings, and their types by name without case or punctuation.
    module: String,
    types: BTreeMap<String, String>,
    /// The aliases that the bindings give their types, each with the name of its type.
    aliases: BTreeMap<String, String>,
    pub(crate) procedures: BTreeMap<u8, Procedure>,
    pub(crate) ies: BTreeMap<u16, Ie>,
}

/// The one type of what has one.
pub(crate) fn alone(alternatives: &BTreeSet<String>) -> Option<String> {
    Some(alternatives.first()?.clone()).filter(|_| alternatives.len() == 1)
}

pub(crate) fn canonical(name: &str) -> String {
    name.chars()
        .filter(char::is_ascii_alphanumeric)
        .flat_map(char::to_lowercase)
        .collect()
}

/// The name of an ASN.1 value after `id-`, as a Rust identifier.
fn ident(id_name: &str) -> String {
    id_name.trim_start_matches("id-").replace('-', "_")
}

impl Registry {
    /// Read the registry of `protocol` from its ASN.1 and the bindings `generated` from it.
    pub(crate) fn read(protocol: &str, generated: &str, asn: &str) -> Result<Self> {
        let declaration = Regex::new(r"(?m)^    pub (?:struct|enum|type) ([A-Za-z][A-Za-z0-9_]*)")?;
        let mut types = BTreeMap::new();
        for c in declaration.captures_iter(generated) {
            types
                .entry(canonical(&c[1]))
                .or_insert_with(|| c[1].to_string());
        }
        // The aliases follow the modules, at the root of the bindings.
        let alias = Regex::new(r"(?m)^pub type ([A-Za-z][A-Za-z0-9_]*) = ([A-Za-z][A-Za-z0-9_]*);")?;
        let aliases = alias.captures_iter(generated);
        let aliases = aliases.map(|c| (c[1].to_string(), c[2].to_string())).collect();
        let mut registry = Self {
            module: protocol.to_ascii_lowercase(),
            types,
            aliases,
            procedures: BTreeMap::new(),
            ies: BTreeMap::new(),
        };
        registry.procedures = registry.read_procedures(protocol, asn)?;
        registry.ies = registry.read_ies(protocol, asn)?;
        Ok(registry)
    }

    /// The path in the crate of the generated type that ASN.1 names `name`.
    pub(crate) fn resolve(&self, name: &str) -> Option<String> {
        let ty = self.types.get(&canonical(name))?;
        Some(format!("crate::{}::{ty}", self.module))
    }

    /// The list: one line for each procedure and for each IE, which the macros
    /// `procedures!` and `ies!` of the crate expand.
    pub(crate) fn list(&self) -> Result<String> {
        // rustfmt leaves the lines of a macro called with braces as they are.
        let mut out = String::from(
            "// Auto-generated by build/registry.rs from ASN.1; do not edit.\nuse crate::macros::{ies, procedures};\n",
        );
        // The procedure code, the name and the criticality, then for each message its
        // direction, its kind, the name that ASN.1 gives it, its type and the IEs of its
        // object set, in brackets: a message without an object set has none.
        writeln!(out, "procedures! {{")?;
        for (code, procedure) in &self.procedures {
            write!(out, "    {code} {}", procedure.name)?;
            if let Some(criticality) = &procedure.criticality {
                write!(out, " {criticality}")?;
            }
            write!(out, " {{")?;
            for ((_, direction, kind), message) in DIRECTIONS.iter().zip(&procedure.messages) {
                if let Some(Message { name, ty, ies }) = message {
                    let kind = format!("{kind}_{}", procedure.name);
                    write!(out, " {direction} {kind} {name:?} {ty}")?;
                    if let Some(ies) = ies {
                        let ies = ies.iter().map(|(id, c, p)| format!("{id} {c} {p}"));
                        let ies: Vec<_> = ies.collect();
                        write!(out, " [{}]", ies.join(", "))?;
                    }
                    write!(out, ";")?;
                }
            }
            writeln!(out, " }}")?;
        }
        writeln!(out, "}}")?;
        // The identifier, the criticality of the IE in a single container when its object
        // sets give it one, the name and the type, the type that the octets of the IE
        // contain, then the names that the macros take the IE by. An IE of an extension
        // container that has several types has them in brackets, each with the types
        // that it extends so.
        writeln!(out, "ies! {{")?;
        for (id, ie) in &self.ies {
            write!(out, "    {id}")?;
            if let Some(criticality) = alone(&ie.items) {
                write!(out, " {criticality}")?;
            }
            write!(out, " {:?}", ie.name)?;
            match (alone(&ie.types), alone(&ie.contents)) {
                (Some(ty), Some(contained)) => write!(out, " {ty}, {contained}")?,
                (Some(ty), None) => write!(out, " {ty}")?,
                (None, None) => {
                    ensure!(
                        ie.macros.is_empty(),
                        "{}: the macros take an IE that has several types",
                        ie.name
                    );
                    // Each type has the types that the IE extends with it, and no type
                    // is extended with two.
                    let extended = ie.extends.values().flatten();
                    let extended: Vec<_> = extended.collect();
                    let distinct: BTreeSet<_> = extended.iter().collect();
                    ensure!(
                        ie.extends.keys().eq(ie.types.iter()) && distinct.len() == extended.len(),
                        "{}: an IE has several types, and not one for each type that it extends",
                        ie.name
                    );
                    let types = ie.extends.iter().map(|(ty, extended)| {
                        let extended: Vec<_> = extended.iter().map(String::as_str).collect();
                        format!("{ty}: {}", extended.join(" "))
                    });
                    write!(out, " [{}]", types.collect::<Vec<_>>().join(", "))?;
                }
                (None, Some(_)) => bail!("{} contains a type and has several", ie.name),
            }
            if !ie.macros.is_empty() {
                write!(out, " => {}", ie.macros.join(" "))?;
            }
            writeln!(out, ";")?;
        }
        writeln!(out, "}}")?;
        ensure!(
            self.procedures
                .values()
                .any(|p| p.messages.iter().any(Option::is_some))
                && !self.ies.is_empty(),
            "empty registry"
        );
        Ok(out)
    }

    /// The procedures: every procedure code, with the criticality and the messages of the
    /// elementary procedure that has it.
    fn read_procedures(&self, protocol: &str, asn: &str) -> Result<BTreeMap<u8, Procedure>> {
        let constant =
            Regex::new(r"(?m)^\s*(id-[A-Za-z][A-Za-z0-9-]*)\s+ProcedureCode\s+::=\s+(\d+)")?;
        let mut codes = BTreeMap::new();
        let mut procedures = BTreeMap::new();
        for c in constant.captures_iter(asn) {
            let code: u8 = c[2].parse()?;
            codes.insert(c[1].to_string(), code);
            let procedure = Procedure {
                name: ident(&c[1]),
                criticality: None,
                messages: Default::default(),
            };
            ensure!(
                procedures.insert(code, procedure).is_none(),
                "procedure code {code} has two names"
            );
        }
        let block = Regex::new(&format!(
            r"(?ms)^[\t ]*[A-Za-z][A-Za-z0-9-]*\s+{protocol}-ELEMENTARY-PROCEDURE\s+::=\s*\{{(.*?)^[\t ]*\}}"
        ))?;
        let reference = Regex::new(r"PROCEDURE CODE\s+(id-[A-Za-z][A-Za-z0-9-]*)")?;
        let criticality = Regex::new(r"\bCRITICALITY\s+(reject|ignore|notify)\b")?;
        for c in block.captures_iter(asn) {
            let code = reference.captures(&c[1]).and_then(|c| codes.get(&c[1]));
            let Some(procedure) = code.and_then(|code| procedures.get_mut(code)) else {
                continue;
            };
            let stated = criticality.captures(&c[1]);
            let stated = stated.ok_or_else(|| anyhow!("{} has no CRITICALITY", procedure.name))?;
            procedure.criticality = Some(stated[1].to_string());
            for ((label, ..), message) in DIRECTIONS.iter().zip(&mut procedure.messages) {
                // The label of an unsuccessful outcome ends with that of a successful one.
                let name = Regex::new(&format!(r"\b{label}\s+([A-Za-z][A-Za-z0-9-]*)"))?;
                if let Some(name) = name.captures(&c[1]) {
                    let ty = self.resolve(&name[1]);
                    let ty = ty.ok_or_else(|| anyhow!("missing message {}", &name[1]))?;
                    *message = Some(Message {
                        name: name[1].to_string(),
                        ty,
                        ies: message_ies(protocol, asn, &name[1])?,
                    });
                }
            }
        }
        Ok(procedures)
    }

    /// The IEs of the object sets, and of the extension sets, which the macros do not reach.
    fn read_ies(&self, protocol: &str, asn: &str) -> Result<BTreeMap<u16, Ie>> {
        let ids = identifiers(asn)?;
        let object = Regex::new(
            r"(?s)\{\s*ID\s+(id-[A-Za-z][A-Za-z0-9-]*)\s+CRITICALITY\s+[A-Za-z-]+\s+(TYPE|EXTENSION)\s+(OCTET\s+STRING(?:\s*\(CONTAINING\s+[A-Za-z][A-Za-z0-9-]*\s*\))?|[A-Za-z][A-Za-z0-9-]*)\s+PRESENCE",
        )?;
        // The type in the OCTET STRING of an IE declared `OCTET STRING (CONTAINING ...)`.
        let containing = Regex::new(r"CONTAINING\s+([A-Za-z][A-Za-z0-9-]*)")?;
        let mut ies: BTreeMap<u16, Ie> = BTreeMap::new();
        // The names of the macros: the identifier and the type that each one stands for.
        let mut names: BTreeMap<String, (u16, String)> = BTreeMap::new();
        // The protocol IEs of each generated type.
        let mut typed: BTreeMap<String, BTreeSet<u16>> = BTreeMap::new();
        for c in object.captures_iter(asn) {
            let Some((id, protocol_ie)) = ids.get(&c[1]).copied() else {
                continue;
            };
            if let Some(ty) = containing.captures(&c[3]).and_then(|c| self.resolve(&c[1])) {
                ies.entry(id).or_default().contents.insert(ty);
            }
            // An inline OCTET STRING, such as the type of an IE that carries a message of
            // the protocol or that contains a type, has no generated type.
            let generated = !c[3].starts_with("OCTET");
            let ty = match generated {
                false => "rasn::types::OctetString".to_string(),
                true => match self.resolve(&c[3]) {
                    Some(ty) => ty,
                    None => continue,
                },
            };
            let ie = ies.entry(id).or_default();
            if ie.name.is_empty() {
                ie.name = c[1].trim_start_matches("id-").to_string();
            }
            ie.types.insert(ty.clone());
            if &c[2] == "TYPE" && protocol_ie {
                // The name of an IE names that IE, in the type that its first object has.
                names.entry(ident(&c[1])).or_insert((id, ty.clone()));
                if generated {
                    typed.entry(ty).or_default().insert(id);
                }
            }
        }
        // The type that an IE has where it extends each type.
        for (constant, extended, ty) in extensions(protocol, asn)? {
            let id = ids.get(&constant).map(|(id, _)| id);
            let ie = id.and_then(|id| ies.get_mut(id));
            if let (Some(ie), Some(extended), Some(ty)) =
                (ie, self.resolve(&extended), self.resolve(&ty))
            {
                let extended = extended.rsplit("::").next().expect("a path").to_string();
                ie.extends.entry(ty).or_default().insert(extended);
            }
        }
        // The criticalities of the IEs that a value holds alone, in a single container.
        for (name, criticalities) in single_containers(protocol, asn)? {
            let id = ids.get(&name).map(|(id, _)| id);
            let ie = id.and_then(|id| ies.get_mut(id));
            ie.ok_or_else(|| anyhow!("{name} names no IE"))?.items = criticalities;
        }
        // The name of a type is an alias only for the one IE of that type: a type that two
        // IEs have could otherwise address either. Nor is it one when an IE has that name,
        // within the reach of the macros or not: the name of an IE names that IE.
        let protocol_ies = ids.iter().filter(|(_, (_, protocol_ie))| *protocol_ie);
        let constants: BTreeSet<String> = protocol_ies.map(|(name, _)| ident(name)).collect();
        for (ty, of) in typed {
            let name = ty.rsplit("::").next().expect("a path").to_string();
            if let Some(id) = of.first().copied().filter(|_| of.len() == 1)
                && !constants.contains(&name)
            {
                names.entry(name).or_insert((id, ty));
            }
        }
        // An alias of a type is a name of that type: it names the IE that the name of
        // the type names, unless an IE has that name itself.
        for (alias, ty) in &self.aliases {
            if let Some(named) = names.get(ty).cloned()
                && !constants.contains(alias)
            {
                names.entry(alias.clone()).or_insert(named);
            }
        }
        for (name, (id, ty)) in names {
            let ie = ies
                .get_mut(&id)
                .ok_or_else(|| anyhow!("{name} names no IE"))?;
            ensure!(
                alone(&ie.types).as_ref() == Some(&ty),
                "{name}: the macros and the inspection have two types for the IE"
            );
            // The IE's own name first, then the name of its type.
            match ident(&ie.name) == name {
                true => ie.macros.insert(0, name),
                false => ie.macros.push(name),
            }
        }
        Ok(ies)
    }
}

/// The identifier of each constant of an IE, and whether it is that of a protocol IE.
fn identifiers(asn: &str) -> Result<BTreeMap<String, (u16, bool)>> {
    let constant = Regex::new(
        r"(?m)^\s*(id-[A-Za-z][A-Za-z0-9-]*)\s+(ProtocolIE-ID|ProtocolExtensionID)\s+::=\s+(\d+)",
    )?;
    constant
        .captures_iter(asn)
        .map(|c| Ok((c[1].to_string(), (c[3].parse()?, &c[2] == "ProtocolIE-ID"))))
        .collect()
}

/// The objects of the extension sets: the constant of the IE, the type that the set
/// extends and the type that the object gives the IE there, each as ASN.1 names it. A
/// set extends the type whose definition has it in its extension container.
fn extensions(protocol: &str, asn: &str) -> Result<Vec<(String, String, String)>> {
    let set = Regex::new(&format!(
        r"(?ms)^[\t ]*([A-Za-z][A-Za-z0-9-]*)\s+{protocol}-PROTOCOL-EXTENSION\s*::=\s*\{{(.*?)^[\t ]*\}}"
    ))?;
    let object = Regex::new(
        r"\{\s*ID\s+(id-[A-Za-z][A-Za-z0-9-]*)\s+CRITICALITY\s+[A-Za-z-]+\s+EXTENSION\s+([A-Za-z][A-Za-z0-9-]*)\s+PRESENCE",
    )?;
    // Each use of a set as an extension container, and each definition of a type: a
    // container is in the definition that starts last before it.
    let container = Regex::new(
        r"ProtocolExtensionContainer\s*\{\s*\{\s*([A-Za-z][A-Za-z0-9-]*)\s*\}\s*\}",
    )?;
    let definition = Regex::new(r"(?m)^([A-Za-z][A-Za-z0-9-]*)\s*::=")?;
    let definitions: Vec<_> = definition.captures_iter(asn).collect();
    let mut extended: BTreeMap<&str, Vec<&str>> = BTreeMap::new();
    for used in container.captures_iter(asn) {
        let at = used.get(0).expect("a match").start();
        let before = definitions.partition_point(|c| c.get(0).expect("a match").start() < at);
        if let Some(definition) = before.checked_sub(1).map(|last| &definitions[last]) {
            let name = definition.get(1).expect("a name").as_str();
            extended.entry(used.get(1).expect("a set").as_str()).or_default().push(name);
        }
    }
    let mut found = Vec::new();
    for set in set.captures_iter(asn) {
        for extended in extended.get(&set[1]).into_iter().flatten() {
            for object in object.captures_iter(&set[2]) {
                found.push((object[1].to_string(), extended.to_string(), object[2].to_string()));
            }
        }
    }
    Ok(found)
}

/// The criticalities that each IE has in the object sets of the single containers, by the
/// constant of the IE. A set of IEs that no `ProtocolIE-Container` has is that of a
/// `ProtocolIE-SingleContainer`, which a value holds alone or as each entry of a list.
fn single_containers(protocol: &str, asn: &str) -> Result<BTreeMap<String, BTreeSet<String>>> {
    let container =
        Regex::new(r"ProtocolIE-Container\s*\{\s*\{\s*([A-Za-z][A-Za-z0-9-]*)\s*\}\s*\}")?;
    let containers = container.captures_iter(asn).map(|c| c[1].to_string());
    let containers: BTreeSet<String> = containers.collect();
    let set = Regex::new(&format!(
        r"(?ms)^[\t ]*([A-Za-z][A-Za-z0-9-]*)\s+{protocol}-PROTOCOL-IES\s*::=\s*\{{(.*?)^[\t ]*\}}"
    ))?;
    let object = Regex::new(
        r"\{\s*ID\s+(id-[A-Za-z][A-Za-z0-9-]*)\s+CRITICALITY\s+(reject|ignore|notify)\b",
    )?;
    let mut items: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
    for set in set.captures_iter(asn) {
        if containers.contains(&set[1]) {
            continue;
        }
        let mut objects = 0;
        for c in object.captures_iter(&set[2]) {
            let criticalities = items.entry(c[1].to_string()).or_default();
            criticalities.insert(c[2].to_string());
            objects += 1;
        }
        ensure!(
            set[2].matches("PRESENCE").count() == objects,
            "{}: an object of the set was not read",
            &set[1]
        );
    }
    Ok(items)
}

/// The IEs of the object set that the message `name` has for its `protocolIEs`: `None`
/// for a message that has no such container, as a private message.
fn message_ies(
    protocol: &str,
    asn: &str,
    name: &str,
) -> Result<Option<Vec<(u16, String, String)>>> {
    let container = Regex::new(&format!(
        r"(?m)^[\t ]*{name}\s*::=\s*SEQUENCE\s*\{{\s*protocolIEs\s+ProtocolIE-Container\s*\{{\s*\{{\s*([A-Za-z][A-Za-z0-9-]*)\s*\}}\s*\}}(\s*,\s*\.\.\.\s*\}})?"
    ))?;
    let Some(set) = container.captures(asn) else {
        return Ok(None);
    };
    // The crate reads the IEs of a PDU without the type of its message: a message is
    // this container, and what a later release adds.
    ensure!(
        set.get(2).is_some(),
        "{name} has more than a container of protocol IEs"
    );
    let block = Regex::new(&format!(
        r"(?ms)^[\t ]*{}\s+{protocol}-PROTOCOL-IES\s*::=\s*\{{(.*?)^[\t ]*\}}",
        &set[1]
    ))?;
    let block = block.captures(asn);
    let block = block.ok_or_else(|| anyhow!("missing object set {}", &set[1]))?;
    let object = Regex::new(
        r"(?s)\{\s*ID\s+(id-[A-Za-z][A-Za-z0-9-]*)\s+CRITICALITY\s+(reject|ignore|notify)\b.*?PRESENCE\s+(mandatory|optional|conditional)\s*\}",
    )?;
    let ids = identifiers(asn)?;
    let mut ies = Vec::new();
    for c in object.captures_iter(&block[1]) {
        let (id, _) = ids
            .get(&c[1])
            .ok_or_else(|| anyhow!("{} has no identifier", &c[1]))?;
        ies.push((*id, c[2].to_string(), c[3].to_string()));
    }
    ensure!(
        block[1].matches("PRESENCE").count() == ies.len(),
        "{}: an object of the set was not read",
        &set[1]
    );
    Ok(Some(ies))
}
